import 'package:flutter/widgets.dart';

class AppI18n {
  AppI18n(this.locale);

  final Locale locale;

  static AppI18n of(BuildContext context) {
    return Localizations.of<AppI18n>(context, AppI18n)!;
  }

  static const LocalizationsDelegate<AppI18n> delegate = _AppI18nDelegate();

  static const supportedLocales = <Locale>[
    Locale('en'),
    Locale('zh'),
  ];

  String tr(String key, {Map<String, String> params = const {}}) {
    final lang = locale.languageCode;
    final dict = _translations[lang] ?? _translations['en']!;
    var text = dict[key] ?? (_translations['en']![key] ?? key);
    params.forEach((k, v) {
      text = text.replaceAll('{$k}', v);
    });
    return text;
  }
}

class _AppI18nDelegate extends LocalizationsDelegate<AppI18n> {
  const _AppI18nDelegate();

  @override
  bool isSupported(Locale locale) {
    return locale.languageCode == 'en' || locale.languageCode == 'zh';
  }

  @override
  Future<AppI18n> load(Locale locale) async {
    return AppI18n(locale);
  }

  @override
  bool shouldReload(covariant LocalizationsDelegate<AppI18n> old) => false;
}

