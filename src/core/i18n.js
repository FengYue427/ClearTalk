// 当前语言
let currentLanguage = 'en';

// 更新页面上的所有 data-i18n 元素
function updatePageTranslations() {
  // 更新普通文本元素
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      const text = t(key);
      if (text && text !== key) {
        el.textContent = text;
      }
    }
  });

  // 更新 placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) {
      const text = t(key);
      if (text && text !== key) {
        el.placeholder = text;
      }
    }
  });

  // 更新 title 属性
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) {
      const text = t(key);
      if (text && text !== key) {
        el.title = text;
      }
    }
  });
}

// 初始化语言设置
export function initI18n() {
  const savedLang = Storage.getSetting('language');
  currentLanguage = (savedLang === 'zh' || savedLang === 'en')
    ? savedLang
    : (navigator.language?.startsWith('zh') ? 'zh' : 'en');
  state.language = currentLanguage;

  // 更新页面上的翻译
  updatePageTranslations();

  // 监听语言变化事件
  events.on('language:changed', () => {
    updatePageTranslations();
  });
}

// 获取翻译文本
export function t(key, params = {}) {
  const lang = state.language || currentLanguage;
  let text = translations[lang]?.[key] || translations['zh']?.[key] || key;
  
  // 替换参数 {n}, {name} 等
  Object.keys(params).forEach(param => {
    text = text.replace(new RegExp(`{${param}}`, 'g'), params[param]);
  });
  
  return text;
}

// 切换语言
export function setLanguage(lang) {
  if (translations[lang]) {
    currentLanguage = lang;
    state.language = lang;

    // 保存到设置
    Storage.setSetting('language', lang);

    // 触发事件
    events.emit('language:changed', lang);

    // 更新 HTML lang 属性
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    document.documentElement.setAttribute('data-lang', lang);

    return true;
  }
  return false;
}

// 获取支持的语言列表
export function getSupportedLanguages() {
  return [
    { code: 'zh', name: '简体中文', nativeName: '简体中文' },
    { code: 'en', name: 'English', nativeName: 'English' }
  ];
}

// 获取当前语言
export function getCurrentLanguage() {
  return currentLanguage;
}

// 检查是否有翻译
export function hasTranslation(key) {
  const lang = state.language || currentLanguage;
  return !!translations[lang]?.[key];
}

export default { t, setLanguage, initI18n, getSupportedLanguages, getCurrentLanguage, hasTranslation };
