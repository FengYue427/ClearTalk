/**
 * 从 assets/scenes/builtin.json 生成 lib/templates/builtin_scenes.dart
 * 运行: npm run scenes:flutter
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const scenes = JSON.parse(
  fs.readFileSync(path.join(root, 'assets', 'scenes', 'builtin.json'), 'utf8')
);

const TYPE_MAP = {
  text: 'FieldType.text',
  textarea: 'FieldType.textarea',
  number: 'FieldType.number',
  select: 'FieldType.select',
  boolean: 'FieldType.boolean',
  date: 'FieldType.date'
};

function toConstName(id) {
  return id.replace(/_([a-z])/g, (_, c) => c.toUpperCase()).replace(/^./, (c) => c.toUpperCase());
}

function escapeDart(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function renderField(f) {
  const lines = [
    `      TemplateField(`,
    `        key: '${f.key}',`,
    `        label: '${escapeDart(f.label)}',`
  ];
  if (f.placeholder) lines.push(`        placeholder: '${escapeDart(f.placeholder)}',`);
  lines.push(`        type: ${TYPE_MAP[f.type] || 'FieldType.text'},`);
  lines.push(`        required: ${f.required},`);
  if (f.hint) lines.push(`        hint: '${escapeDart(f.hint)}',`);
  if (f.options?.length) {
    lines.push(`        options: [${f.options.map((o) => `'${escapeDart(o)}'`).join(', ')}],`);
  }
  lines.push(`      ),`);
  return lines.join('\n');
}

function renderScene(scene) {
  const constName = `_${toConstName(scene.id).charAt(0).toLowerCase()}${toConstName(scene.id).slice(1)}`;
  const fields = scene.fields.map(renderField).join('\n');
  return `  static const ${constName} = SceneTemplate(
    id: '${scene.id}',
    name: '${escapeDart(scene.name)}',
    category: '${escapeDart(scene.category)}',
    description: '${escapeDart(scene.description)}',
    fields: [
${fields}
    ],
  );`;
}

const sceneConsts = scenes.map(renderScene).join('\n\n');
const allRefs = scenes
  .map((s) => {
    const n = `_${toConstName(s.id).charAt(0).toLowerCase()}${toConstName(s.id).slice(1)}`;
    return `    ${n},`;
  })
  .join('\n');

const categories = [...new Set(scenes.map((s) => s.category))];

const out = `// GENERATED by scripts/build-flutter-scenes.mjs — do not edit by hand
// Source: assets/scenes/builtin.json (${scenes.length} scenes)
// Regenerate: npm run scenes:flutter

import '../models/scene_template.dart';

class BuiltinScenes {
  static const all = [
${allRefs}
  ];

  static SceneTemplate? findById(String id) {
    try {
      return all.firstWhere((s) => s.id == id);
    } catch (_) {
      return null;
    }
  }

  static List<SceneTemplate> byCategory(String category) {
    return all.where((s) => s.category == category).toList();
  }

  static List<String> get categories => const [
${categories.map((c) => `    '${escapeDart(c)}',`).join('\n')}
  ];

${sceneConsts}
}
`;

const outPath = path.join(root, 'lib', 'templates', 'builtin_scenes.dart');
fs.writeFileSync(outPath, out, 'utf8');
console.log(`Wrote ${scenes.length} scenes → ${outPath}`);
